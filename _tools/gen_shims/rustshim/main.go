// Command rustshim generates crates/ets_shim, the Rust counterpart of the Go shim modules: a facade crate that
// re-exports the tsrs crates (and selected items) listed in config.json, so that the Effect Rust crates depend on
// ets_shim only and never on a tsrs_* crate directly. `repoctl submodules setup` runs it after patching the tsrs
// checkout; the generated crate is committed, like shim/, and must never be edited by hand.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

const (
	generatedMarker = ".generated-by-gen-shims"
	generatedHeader = "Code generated by _tools/gen_shims/rustshim from _tools/gen_shims/rustshim/config.json. DO NOT EDIT."
)

// Config is config.json.
type Config struct {
	// Crates are the tsrs crates re-exported as modules: `tsrs_checker` becomes `ets_shim::checker`.
	Crates []string `json:"crates"`
	// Items are paths re-exported at the crate root (`tsrs_core::P` becomes `ets_shim::P`). Each path must start
	// with one of Crates.
	Items []string `json:"items"`
}

var (
	crateNamePattern = regexp.MustCompile(`^tsrs_[a-z0-9_]+$`)
	itemPathPattern  = regexp.MustCompile(`^(tsrs_[a-z0-9_]+)(::[A-Za-z_][A-Za-z0-9_]*)+$`)
	packageName      = regexp.MustCompile(`(?m)^name\s*=\s*"([^"]+)"`)
)

func moduleName(crate string) string {
	return strings.TrimPrefix(crate, "tsrs_")
}

func parseConfig(data []byte) (Config, error) {
	var config Config
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&config); err != nil {
		return Config{}, err
	}
	if len(config.Crates) == 0 {
		return Config{}, fmt.Errorf("config lists no crates")
	}
	seen := map[string]bool{}
	for _, crate := range config.Crates {
		if !crateNamePattern.MatchString(crate) {
			return Config{}, fmt.Errorf("crate %q is not a tsrs_* crate name", crate)
		}
		if seen[crate] {
			return Config{}, fmt.Errorf("crate %q is listed twice", crate)
		}
		seen[crate] = true
	}
	items := map[string]bool{}
	for _, item := range config.Items {
		match := itemPathPattern.FindStringSubmatch(item)
		if match == nil {
			return Config{}, fmt.Errorf("item %q is not a path into a tsrs crate", item)
		}
		if !seen[match[1]] {
			return Config{}, fmt.Errorf("item %q names crate %s, which is not in crates", item, match[1])
		}
		if items[item] {
			return Config{}, fmt.Errorf("item %q is listed twice", item)
		}
		items[item] = true
	}
	config.Crates = slices.Sorted(slices.Values(config.Crates))
	config.Items = slices.Sorted(slices.Values(config.Items))
	return config, nil
}

// checkCrates verifies that every configured crate exists in the tsrs checkout under its own name.
func checkCrates(tsrsRoot string, config Config) error {
	for _, crate := range config.Crates {
		manifest := filepath.Join(tsrsRoot, "crates", crate, "Cargo.toml")
		data, err := os.ReadFile(manifest)
		if err != nil {
			return fmt.Errorf("tsrs crate %s: %w", crate, err)
		}
		match := packageName.FindSubmatch(data)
		if match == nil || string(match[1]) != crate {
			return fmt.Errorf("%s does not declare package %s", manifest, crate)
		}
	}
	return nil
}

// renderCargoToml renders crates/ets_shim/Cargo.toml; tsrsFromCrate is the tsrs checkout relative to the crate.
func renderCargoToml(config Config, tsrsFromCrate string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", generatedHeader)
	b.WriteString("[package]\n")
	b.WriteString("name = \"ets_shim\"\n")
	b.WriteString("version.workspace = true\n")
	b.WriteString("edition.workspace = true\n")
	b.WriteString("rust-version.workspace = true\n")
	b.WriteString("license.workspace = true\n")
	b.WriteString("publish.workspace = true\n")
	b.WriteString("description = \"Generated facade over the patched tsrs crates (the Rust counterpart of shim/)\"\n\n")
	b.WriteString("[lints]\nworkspace = true\n\n")
	b.WriteString("[dependencies]\n")
	for _, crate := range config.Crates {
		fmt.Fprintf(&b, "%s = { path = %q }\n", crate, filepath.ToSlash(filepath.Join(tsrsFromCrate, "crates", crate)))
	}
	return b.String()
}

func renderLib(config Config) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\n", generatedHeader)
	b.WriteString("//! The tsrs facade of the Rust port: Effect crates reach tsrs only through these re-exports.\n\n")
	for _, crate := range config.Crates {
		fmt.Fprintf(&b, "pub use %s as %s;\n", crate, moduleName(crate))
	}
	if len(config.Items) > 0 {
		b.WriteString("\n")
		for _, item := range config.Items {
			fmt.Fprintf(&b, "pub use %s;\n", item)
		}
	}
	return b.String()
}

func writeIfChanged(path string, content string) error {
	if existing, err := os.ReadFile(path); err == nil && string(existing) == content {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

func generate(repositoryRoot, tsrsRoot, configPath string) error {
	data, err := os.ReadFile(configPath)
	if err != nil {
		return err
	}
	config, err := parseConfig(data)
	if err != nil {
		return fmt.Errorf("%s: %w", configPath, err)
	}
	if err := checkCrates(tsrsRoot, config); err != nil {
		return err
	}
	output := filepath.Join(repositoryRoot, "crates", "ets_shim")
	tsrsFromCrate, err := filepath.Rel(output, tsrsRoot)
	if err != nil {
		return err
	}
	files := map[string]string{
		"Cargo.toml":    renderCargoToml(config, tsrsFromCrate),
		"src/lib.rs":    renderLib(config),
		generatedMarker: "Generated by _tools/gen_shims/rustshim. DO NOT EDIT.\n",
	}
	// Remove whatever an earlier generation left that this one does not write; unchanged files keep their mtime.
	err = filepath.WalkDir(output, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if entry.IsDir() {
			return nil
		}
		relative, err := filepath.Rel(output, path)
		if err != nil {
			return err
		}
		if _, ok := files[filepath.ToSlash(relative)]; !ok {
			return os.Remove(path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	for name, content := range files {
		if err := writeIfChanged(filepath.Join(output, name), content); err != nil {
			return err
		}
	}
	fmt.Printf("Generated crates/ets_shim (%d tsrs crates, %d items)\n", len(config.Crates), len(config.Items))
	return nil
}

func main() {
	var repositoryRoot, tsrsRoot, configPath string
	flag.StringVar(&repositoryRoot, "repository-root", "", "path to the repository root")
	flag.StringVar(&tsrsRoot, "tsrs-root", "", "path to the patched tsrs checkout (default <repository-root>/tsrs)")
	flag.StringVar(&configPath, "config", "", "path to config.json (default <repository-root>/_tools/gen_shims/rustshim/config.json)")
	flag.Parse()
	if repositoryRoot == "" {
		log.Fatal("--repository-root is required")
	}
	repositoryRoot, err := filepath.Abs(repositoryRoot)
	if err != nil {
		log.Fatal(err)
	}
	if tsrsRoot == "" {
		tsrsRoot = filepath.Join(repositoryRoot, "tsrs")
	}
	if configPath == "" {
		configPath = filepath.Join(repositoryRoot, "_tools", "gen_shims", "rustshim", "config.json")
	}
	tsrsRoot, err = filepath.Abs(tsrsRoot)
	if err != nil {
		log.Fatal(err)
	}
	if err := generate(repositoryRoot, tsrsRoot, configPath); err != nil {
		log.Fatal(err)
	}
}
